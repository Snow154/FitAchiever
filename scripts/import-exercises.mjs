// Development-only importer. Prints TypeScript; never runs inside the app.
const sourceUrl = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json";
const selectedIds = [
  "Barbell_Curl", "Barbell_Deadlift", "Barbell_Hip_Thrust",
  "Bent_Over_Barbell_Row", "Cable_Crunch", "Crunches",
  "Dips_-_Triceps_Version", "Dumbbell_Bicep_Curl", "Dumbbell_Flyes",
  "Dumbbell_Lunges", "Face_Pull", "Front_Barbell_Squat",
  "Hanging_Leg_Raise", "Leg_Extensions", "Leg_Press", "Lying_Leg_Curls",
  "Lying_Triceps_Press", "One-Arm_Dumbbell_Row", "Preacher_Curl",
  "Pullups", "Pushups", "Reverse_Flyes", "Romanian_Deadlift",
  "Seated_Cable_Rows", "Seated_Calf_Raise", "Seated_Leg_Curl",
  "Side_Lateral_Raise", "Standing_Calf_Raises", "Triceps_Pushdown",
  "Wide-Grip_Lat_Pulldown",
  "Barbell_Incline_Bench_Press_-_Medium_Grip", "Incline_Dumbbell_Press",
  "Cable_Crossover", "Machine_Bench_Press",
  "Chin-Up", "Close-Grip_Front_Lat_Pulldown", "Straight-Arm_Pulldown",
  "T-Bar_Row_with_Handle",
  "Arnold_Dumbbell_Press", "Front_Dumbbell_Raise", "Barbell_Shrug",
  "Concentration_Curls", "Incline_Dumbbell_Curl", "EZ-Bar_Curl",
  "Close-Grip_Barbell_Bench_Press", "Tricep_Dumbbell_Kickback",
  "Triceps_Overhead_Extension_with_Rope",
  "Hack_Squat", "Goblet_Squat", "Dumbbell_Step_Ups",
  "Barbell_Glute_Bridge", "Single_Leg_Glute_Bridge",
  "Ab_Crunch_Machine", "Reverse_Crunch",
];
const muscleMap = {
  chest: "chest", lats: "back", "middle back": "back", "lower back": "back",
  traps: "back", shoulders: "shoulders", biceps: "biceps", triceps: "triceps",
  quadriceps: "quadriceps", hamstrings: "hamstrings", glutes: "glutes",
  calves: "calves", abdominals: "core",
};
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`Download failed: ${response.status}`);
const source = await response.json();
const exercises = selectedIds.map((sourceId) => {
  const entry = source.find((item) => item.id === sourceId);
  if (!entry) throw new Error(`Missing source exercise: ${sourceId}`);
  const primaryMuscle = muscleMap[entry.primaryMuscles[0]];
  if (!primaryMuscle || !entry.equipment) {
    throw new Error(`Unsupported muscle or missing equipment: ${sourceId}`);
  }
  return {
    id: sourceId.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
    name: entry.name,
    primaryMuscle,
    equipment: entry.equipment === "body only" ? "bodyweight" : entry.equipment,
  };
});
if (new Set(exercises.map((exercise) => exercise.id)).size !== exercises.length) {
  throw new Error("Duplicate generated IDs");
}
console.log(`// Generated by scripts/import-exercises.mjs. Source and license: docs/EXERCISE_DATA.md.
import type { Exercise } from "@/types/exercise";

export const importedExercises = ${JSON.stringify(exercises, null, 2)} satisfies Exercise[];`);
